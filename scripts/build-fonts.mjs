/**
 * Turns the embeddable fonts (src/client/assets/fonts/*.ttf) into modules the
 * client can import lazily: one per face, exporting the file as base64.
 *
 * The page's bundle is JavaScript only, so a font travels as a module of its
 * own, split into its own chunk and loaded the first time a PDF needs text
 * the standard fonts cannot set (see src/client/engine/fonts/index.ts). The
 * output is generated and not committed; `npm run build`, `dev`, `test` and
 * `typecheck` all run this first. Running it twice changes nothing.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = join(root, 'src/client/assets/fonts')
const outDir = join(root, 'src/client/engine/fonts/data')

mkdirSync(outDir, { recursive: true })

const write = (path, content) => {
    let current = null
    try {
        current = readFileSync(path, 'utf8')
    } catch {}
    if (current !== content) writeFileSync(path, content)
}

const fonts = readdirSync(sourceDir).filter(file => file.endsWith('.ttf'))
for (const file of fonts) {
    const name = basename(file, '.ttf')
        .replace(/([a-z])([A-Z])/g, '$1-$2')
        .toLowerCase()
    const base64 = readFileSync(join(sourceDir, file)).toString('base64')
    write(
        join(outDir, `${name}.ts`),
        `// Generated by scripts/build-fonts.mjs from src/client/assets/fonts/${file}. Do not edit.\n` +
            `// The font is licensed under the SIL Open Font License 1.1; see src/client/assets/fonts/OFL.txt.\n` +
            `export default ${JSON.stringify(base64)};\n`
    )
}
console.log(`[fonts] ${fonts.length} fonts → src/client/engine/fonts/data/`)
